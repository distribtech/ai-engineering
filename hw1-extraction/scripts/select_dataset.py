# 10 кандидатів у golden set: різні типи, від 43 до ~1400 символів, з опечатками й іншою мовою.
GOLDEN = [3536, 915, 2593, 4435, 3571, 4332, 3492, 2333, 4442, 2088]


def main() -> None:
    assert len(SELECTION) == 30, len(SELECTION)
    assert set(GOLDEN) <= set(SELECTION), set(GOLDEN) - set(SELECTION)
    assert len(GOLDEN) == 10

    with SOURCE.open(encoding="utf-8") as f:
        posts = {p["id"]: p for p in map(json.loads, f)}

    missing = set(SELECTION) - set(posts)
    if missing:
        raise SystemExit(f"Немає в {SOURCE.name}: {sorted(missing)}")

    rows = []
    for post_id in sorted(SELECTION):
        p = posts[post_id]
        post_type, reason = SELECTION[post_id]
        rows.append({
            "id": p["id"],
            "url": p["url"],
            "date": p["date"],
            "forwarded_from": p["forwarded_from"],
            "text": p["text"],
            "chars": len(p["text"]),
            "type_hint": post_type,
            "selection_reason": reason,
            "golden_candidate": post_id in GOLDEN,
        })

    with TARGET.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"{len(rows)} постів -> {TARGET.relative_to(ROOT)}; golden-кандидатів: {sum(r['golden_candidate'] for r in rows)}")


if __name__ == "__main__":
    main()
